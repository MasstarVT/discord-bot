// Generates rust/crates/bot-config/src/tables.rs from the JS registries in src/config/*.js,
// so the Rust tables are never typed by hand (emoji variation selectors, order, values).
// Run from the repo root: node rust/fixtures/gen/bot-config-tables.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const imp = (p) => import(pathToFileURL(join(ROOT, p)).href);
const constants = await imp('src/config/constants.js');
const customIds = await imp('src/config/customIds.js');
const hookPoints = await imp('src/config/hookPoints.js');
const jobTypes = await imp('src/config/jobTypes.js');
const modules = await imp('src/config/modules.js');

const str = (s) => JSON.stringify(s); // JSON string literals are valid Rust string literals for this data
const pascal = (s) => s.split(/[.\-:]/).map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
const out = [];
const w = (line = '') => out.push(line);

function stringEnum(name, doc, values) {
  w(`/// ${doc}`);
  w('#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]');
  w(`pub enum ${name} {`);
  for (const v of values) w(`    /// \`${v}\``), w(`    ${pascal(v)},`);
  w('}');
  w();
  w(`impl ${name} {`);
  w(`    /// Every variant, in the JS declaration order.`);
  w(`    pub const ALL: [${name}; ${values.length}] = [${values.map((v) => `${name}::${pascal(v)}`).join(', ')}];`);
  w();
  w('    /// The exact JS string.');
  w('    pub const fn as_str(self) -> &\'static str {');
  w('        match self {');
  for (const v of values) w(`            ${name}::${pascal(v)} => ${str(v)},`);
  w('        }');
  w('    }');
  w();
  w('    /// Parses the exact JS string (case-sensitive); `None` for anything else.');
  w('    pub fn from_name(s: &str) -> Option<Self> {');
  w('        match s {');
  for (const v of values) w(`            ${str(v)} => Some(${name}::${pascal(v)}),`);
  w('            _ => None,');
  w('        }');
  w('    }');
  w('}');
  w();
}

w('// @generated by rust/fixtures/gen/bot-config-tables.mjs from src/config/*.js. Do not edit by hand;');
w('// re-run the script after changing the JS registries.');
w();
w('use crate::custom_ids::{ComponentType, CustomIdKind, PrefixInfo};');
w('use crate::job_types::JobTypeInfo;');
w('use crate::modules::ModuleInfo;');
w();

// ── Module keys and MODULES ──────────────────────────────────────────────────
stringEnum('ModuleKey', 'A `MODULES` key (src/config/modules.js).', modules.MODULE_NAMES);
w('/// `MODULES` in declaration order (src/config/modules.js).');
w(`pub static MODULES: [ModuleInfo; ${modules.MODULE_NAMES.length}] = [`);
for (const k of modules.MODULE_NAMES) {
  const m = modules.MODULES[k];
  w(`    ModuleInfo { key: ModuleKey::${pascal(k)}, flag: ${str(m.flag)}, label: ${str(m.label)}, emoji: ${str(m.emoji)}, mee6: ${str(m.mee6)}, config_command: ${str(m.configCommand)}, default: ${m.default} },`);
}
w('];');
w();
const dms = Object.keys(constants.DEFAULT_MODULE_SETTINGS);
w('/// `DEFAULT_MODULE_SETTINGS` in declaration order (src/config/constants.js).');
w(`pub static DEFAULT_MODULE_SETTINGS: [(ModuleKey, bool); ${dms.length}] = [`);
for (const k of dms) w(`    (ModuleKey::${pascal(k)}, ${constants.DEFAULT_MODULE_SETTINGS[k]}),`);
w('];');
w();

// ── LIMITS ───────────────────────────────────────────────────────────────────
const limitKeys = Object.keys(constants.LIMITS);
w('/// `LIMITS` (src/config/constants.js): per-guild caps. Use these, never a hard-coded number.');
w('pub mod limits {');
for (const k of limitKeys) w(`    pub const ${k}: usize = ${constants.LIMITS[k]};`);
w('}');
w();
w('/// `LIMITS` as a name/value table in declaration order.');
w(`pub static LIMITS: [(&str, usize); ${limitKeys.length}] = [`);
for (const k of limitKeys) w(`    (${str(k)}, limits::${k}),`);
w('];');
w();

// ── CUSTOM_ID_PREFIXES ───────────────────────────────────────────────────────
const typeV = { button: 'Button', select: 'Select', modal: 'Modal', field: 'Field' };
const kindV = { persistent: 'Persistent', collector: 'Collector', field: 'Field' };
const prefixes = Object.keys(customIds.CUSTOM_ID_PREFIXES);
w('/// `CUSTOM_ID_PREFIXES` in declaration order (src/config/customIds.js).');
w(`pub static CUSTOM_ID_PREFIXES: [PrefixInfo; ${prefixes.length}] = [`);
for (const p of prefixes) {
  const i = customIds.CUSTOM_ID_PREFIXES[p];
  w(`    PrefixInfo { prefix: ${str(p)}, owner: ${str(i.owner)}, types: &[${i.types.map((t) => `ComponentType::${typeV[t]}`).join(', ')}], kind: CustomIdKind::${kindV[i.kind]} },`);
}
w('];');
w();

// ── HOOK_ORDER ───────────────────────────────────────────────────────────────
const events = Object.keys(hookPoints.HOOK_ORDER);
stringEnum('HookPoint', 'A hook point (event) of `HOOK_ORDER` (src/config/hookPoints.js).', events);
w('/// `HOOK_ORDER` in declaration order: the order plugin hooks run for each event.');
w(`pub static HOOK_ORDER: [(HookPoint, &[&str]); ${events.length}] = [`);
for (const e of events) w(`    (HookPoint::${pascal(e)}, &[${hookPoints.HOOK_ORDER[e].map(str).join(', ')}]),`);
w('];');
w();
w('/// `INTERNAL_HOOK_POINTS`: emitted by services, not by a gateway event file.');
w(`pub static INTERNAL_HOOK_POINTS: [HookPoint; ${hookPoints.INTERNAL_HOOK_POINTS.length}] = [${hookPoints.INTERNAL_HOOK_POINTS.map((e) => `HookPoint::${pascal(e)}`).join(', ')}];`);
w('/// `SYNTHETIC_HOOK_POINTS`: emitted by runGuildReady, not by an event file.');
w(`pub static SYNTHETIC_HOOK_POINTS: [HookPoint; ${hookPoints.SYNTHETIC_HOOK_POINTS.length}] = [${hookPoints.SYNTHETIC_HOOK_POINTS.map((e) => `HookPoint::${pascal(e)}`).join(', ')}];`);
w();

// ── JOB_TYPES ────────────────────────────────────────────────────────────────
const jobs = Object.keys(jobTypes.JOB_TYPES);
stringEnum('JobType', 'A `JOB_TYPES` key (src/config/jobTypes.js), stored in `ScheduledJob.type`.', jobs);
w('/// `JOB_TYPES` in declaration order (src/config/jobTypes.js).');
w(`pub static JOB_TYPES: [JobTypeInfo; ${jobs.length}] = [`);
for (const j of jobs) {
  const i = jobTypes.JOB_TYPES[j];
  w(`    JobTypeInfo { job_type: JobType::${pascal(j)}, owner: ${str(i.owner)}, recurring: ${i.recurring}, dedupe: ${str(i.dedupe)}, interactive: ${i.interactive === true} },`);
}
w('];');
w();
w('/// `RECURRING_JOB_TYPES`: re-seed themselves and are cancelled when the bot leaves a guild.');
w(`pub static RECURRING_JOB_TYPES: [JobType; ${jobTypes.RECURRING_JOB_TYPES.length}] = [${jobTypes.RECURRING_JOB_TYPES.map((j) => `JobType::${pascal(j)}`).join(', ')}];`);
w('/// `INTERACTIVE_JOB_TYPES`: jobs someone is waiting for (claimed by their own fast loop).');
w(`pub static INTERACTIVE_JOB_TYPES: [JobType; ${jobTypes.INTERACTIVE_JOB_TYPES.length}] = [${jobTypes.INTERACTIVE_JOB_TYPES.map((j) => `JobType::${pascal(j)}`).join(', ')}];`);

const target = join(ROOT, 'rust', 'crates', 'bot-config', 'src', 'tables.rs');
writeFileSync(target, `${out.join('\n')}\n`);
process.stdout.write(`tables.rs: ${out.length} lines\n`);
