// Generates rust/crates/bot-db/src/models.rs from Prisma's own data model description
// (rust/fixtures/golden/prisma-dmmf.json, written by dump-golden.mjs).
//   node rust/fixtures/gen/bot-db-models.mjs        (from the repository root)
// The output is committed; re-run after the schema (and the DMMF dump) changes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const RUST = resolve(HERE, '..', '..');
const dmmf = JSON.parse(readFileSync(join(RUST, 'fixtures', 'golden', 'prisma-dmmf.json'), 'utf8'));
const OUT = join(RUST, 'crates', 'bot-db', 'src', 'models.rs');

const KEYWORDS = new Set(('as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref '
  + 'return self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro '
  + 'override priv typeof unsized virtual yield try gen').split(' '));

const enumNames = new Set(dmmf.enums.map((e) => e.name));
const snake = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toLowerCase();
const ident = (name) => { const s = snake(name); return KEYWORDS.has(s) ? `r#${s}` : s; };
const pascal = (label) => label.toLowerCase().split('_').filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const str = (s) => JSON.stringify(s);

function scalarKind(f) {
  if (f.kind === 'enum') return `ScalarKind::Enum(${str(f.type)})`;
  return `ScalarKind::${f.type}`;
}

function baseRustType(f) {
  if (f.kind === 'enum') return f.type;
  switch (f.type) {
    case 'String': return 'String';
    case 'Int': return 'i32';
    case 'BigInt': return 'i64';
    case 'Float': return 'f64';
    case 'Boolean': return 'bool';
    case 'DateTime': return 'DateTime<Utc>';
    case 'Json': return 'serde_json::Value';
    default: throw new Error(`unsupported scalar ${f.type}`);
  }
}

function rustType(f) {
  const base = baseRustType(f);
  if (f.isList) return `Vec<${base}>`;
  return f.isRequired ? base : `Option<${base}>`;
}

/** serde helper module for a field, or null. */
function serdeWith(f) {
  const suffix = f.isList ? '_vec' : (f.isRequired ? '' : '_opt');
  switch (f.type) {
    case 'DateTime': return `crate::serde_js::date${suffix}`;
    case 'Int': return `crate::serde_js::int${suffix}`;
    case 'BigInt': return `crate::serde_js::bigint${suffix}`;
    case 'Float': return `crate::serde_js::float${suffix}`;
    default: return null;
  }
}

function clientDefault(f) {
  if (f.isUpdatedAt) return 'ClientDefault::UpdatedAt';
  const d = f.default;
  if (d && typeof d === 'object' && !Array.isArray(d)) {
    if (d.name === 'cuid') return 'ClientDefault::Cuid';
    if (d.name === 'uuid') return 'ClientDefault::Uuid';
    if (d.name === 'now') return 'ClientDefault::Now';
    if (d.name === 'autoincrement') return 'ClientDefault::Database';
    throw new Error(`unsupported default function ${d.name}`);
  }
  return f.hasDefaultValue ? 'ClientDefault::Database' : 'ClientDefault::None';
}

function defaultJson(f) {
  if (!f.hasDefaultValue) return 'None';
  const d = f.default;
  if (d && typeof d === 'object' && !Array.isArray(d)) return 'None';
  return `Some(${str(JSON.stringify(d))})`;
}

function getExpr(f) {
  const col = str(f.dbName ?? f.name);
  if (f.type === 'DateTime') {
    if (f.isList) return `row.try_get::<Option<Vec<NaiveDateTime>>, _>(${col})?.unwrap_or_default().into_iter().map(|d| d.and_utc()).collect()`;
    return f.isRequired
      ? `row.try_get::<NaiveDateTime, _>(${col})?.and_utc()`
      : `row.try_get::<Option<NaiveDateTime>, _>(${col})?.map(|d| d.and_utc())`;
  }
  // Prisma creates scalar-list columns without NOT NULL; a NULL list reads as [] like Prisma returns it.
  if (f.isList) return `row.try_get::<Option<${rustType(f)}>, _>(${col})?.unwrap_or_default()`;
  return `row.try_get(${col})?`;
}

const lines = [];
const out = (s = '') => lines.push(s);

out('// @generated by rust/fixtures/gen/bot-db-models.mjs from rust/fixtures/golden/prisma-dmmf.json. Do not edit by hand.');
out('//! Every model and enum of `prisma/schema.prisma` as Rust types (see `schema.rs` for the metadata types).');
out('#![allow(clippy::all)]');
out();
out('use chrono::{DateTime, NaiveDateTime, Utc};');
out('use serde::{Deserialize, Serialize};');
out('use sqlx::Row;');
out('use sqlx::postgres::PgRow;');
out();
out('use crate::schema::{ClientDefault, ColumnInfo, EnumInfo, Model, ModelInfo, ScalarKind};');
out();

// ── Enums ──
out('// ── Enums ───────────────────────────────────────────────────────────────────');
out();
for (const e of dmmf.enums) {
  const pgName = e.dbName ?? e.name;
  out(`/// PostgreSQL enum type \`"${pgName}"\`.`);
  out('#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, sqlx::Type)]');
  out(`#[sqlx(type_name = ${str(`"${pgName}"`)})]`);
  out(`pub enum ${e.name} {`);
  for (const v of e.values) {
    const label = v.dbName ?? v.name;
    out(`    #[serde(rename = ${str(v.name)})]`);
    out(`    #[sqlx(rename = ${str(label)})]`);
    out(`    ${pascal(v.name)},`);
  }
  out('}');
  out();
  out(`impl ${e.name} {`);
  out(`    /// The PostgreSQL type name (unquoted).`);
  out(`    pub const TYPE_NAME: &'static str = ${str(pgName)};`);
  out(`    /// Every value, in schema order.`);
  out(`    pub const ALL: &'static [${e.name}] = &[${e.values.map((v) => `${e.name}::${pascal(v.name)}`).join(', ')}];`);
  out(`    /// The label as stored in PostgreSQL and written by the JS bot.`);
  out(`    pub const fn as_str(self) -> &'static str {`);
  out('        match self {');
  for (const v of e.values) out(`            ${e.name}::${pascal(v.name)} => ${str(v.dbName ?? v.name)},`);
  out('        }');
  out('    }');
  out(`    /// Parses a label (exact, case-sensitive like Prisma).`);
  out(`    pub fn parse(label: &str) -> Option<Self> {`);
  out('        match label {');
  for (const v of e.values) out(`            ${str(v.dbName ?? v.name)} => Some(${e.name}::${pascal(v.name)}),`);
  out('            _ => None,');
  out('        }');
  out('    }');
  out('}');
  out();
  out(`impl std::fmt::Display for ${e.name} {`);
  out('    fn fmt(&self, f: &mut std::fmt::Formatter<\'_>) -> std::fmt::Result { f.write_str(self.as_str()) }');
  out('}');
  out();
  out(`impl std::str::FromStr for ${e.name} {`);
  out('    type Err = crate::DbError;');
  out(`    fn from_str(s: &str) -> Result<Self, Self::Err> { Self::parse(s).ok_or_else(|| crate::DbError::InvalidValue { column: ${str(e.name)}.into(), reason: format!("unknown enum label {s:?}") }) }`);
  out('}');
  out();
}

out('/// Every enum of the schema.');
out('pub static ENUMS: &[EnumInfo] = &[');
for (const e of dmmf.enums) {
  out(`    EnumInfo { name: ${str(e.dbName ?? e.name)}, values: &[${e.values.map((v) => str(v.dbName ?? v.name)).join(', ')}] },`);
}
out('];');
out();

// ── Models ──
out('// ── Models ──────────────────────────────────────────────────────────────────');
out();
const infoNames = [];
for (const m of dmmf.models) {
  const table = m.dbName ?? m.name;
  const fields = m.fields.filter((f) => f.kind !== 'object');
  for (const f of fields) {
    if (f.kind === 'enum' && !enumNames.has(f.type)) throw new Error(`unknown enum ${f.type}`);
  }
  const pk = m.primaryKey ? m.primaryKey.fields : fields.filter((f) => f.isId).map((f) => f.name);
  const uniques = [
    ...fields.filter((f) => f.isUnique).map((f) => [f.name]),
    ...(m.uniqueFields ?? []),
  ];
  const infoName = `${snake(m.name).toUpperCase()}_INFO`;
  infoNames.push(infoName);

  out(`/// Table \`"${table}"\`.`);
  out('#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]');
  out(`pub struct ${m.name} {`);
  for (const f of fields) {
    const attrs = [`rename = ${str(f.name)}`];
    const w = serdeWith(f);
    if (w) attrs.push(`with = ${str(w)}`);
    if (!f.isRequired || f.isList) attrs.push('default');
    out(`    #[serde(${attrs.join(', ')})]`);
    out(`    pub ${ident(f.name)}: ${rustType(f)},`);
  }
  out('}');
  out();
  out(`impl<'r> sqlx::FromRow<'r, PgRow> for ${m.name} {`);
  out('    fn from_row(row: &\'r PgRow) -> Result<Self, sqlx::Error> {');
  out('        Ok(Self {');
  for (const f of fields) out(`            ${ident(f.name)}: ${getExpr(f)},`);
  out('        })');
  out('    }');
  out('}');
  out();
  out(`/// Metadata of \`${m.name}\`.`);
  out(`pub static ${infoName}: ModelInfo = ModelInfo {`);
  out(`    name: ${str(m.name)},`);
  out(`    table: ${str(table)},`);
  out('    columns: &[');
  for (const f of fields) {
    out(`        ColumnInfo { name: ${str(f.dbName ?? f.name)}, field: ${str(f.name)}, kind: ${scalarKind(f)}, list: ${f.isList}, nullable: ${!f.isRequired}, `
      + `has_default: ${f.hasDefaultValue}, client_default: ${clientDefault(f)}, default_json: ${defaultJson(f)}, is_id: ${f.isId}, is_unique: ${f.isUnique}, updated_at: ${f.isUpdatedAt} },`);
  }
  out('    ],');
  out(`    primary_key: &[${pk.map(str).join(', ')}],`);
  out(`    unique: &[${uniques.map((u) => `&[${u.map(str).join(', ')}]`).join(', ')}],`);
  out('};');
  out();
  out(`impl ${m.name} {`);
  out(`    /// Quoted-identifier table name.`);
  out(`    pub const TABLE: &'static str = ${str(table)};`);
  out(`    /// Every column, in schema order.`);
  out(`    pub const COLUMNS: &'static [ColumnInfo] = ${infoName}.columns;`);
  out('}');
  out();
  out(`impl Model for ${m.name} {`);
  out(`    fn info() -> &'static ModelInfo { &${infoName} }`);
  out('}');
  out();
}

// GuildSettings extras.
const gs = dmmf.models.find((m) => m.name === 'GuildSettings');
const boolFields = gs.fields.filter((f) => f.kind === 'scalar' && f.type === 'Boolean' && !f.isList);
out('impl GuildSettings {');
out('    /// The value of a Boolean column by its (Prisma) name; `None` for an unknown or non-Boolean column.');
out('    /// A nullable Boolean column (`captchaLockdownPrior`) gives its raw value: `None` when NULL, since the JS tells');
out('    /// `null` and `false` apart there.');
out('    pub fn flag(&self, column: &str) -> Option<bool> {');
out('        match column {');
for (const f of boolFields) {
  out(f.isRequired ? `            ${str(f.name)} => Some(self.${ident(f.name)}),` : `            ${str(f.name)} => self.${ident(f.name)},`);
}
out('            _ => None,');
out('        }');
out('    }');
out();
out('    /// Names of every Boolean column.');
out(`    pub const BOOLEAN_COLUMNS: &'static [&'static str] = &[${boolFields.map((f) => str(f.name)).join(', ')}];`);
out();
out('    /// The JSON object the JS bot caches in Redis for this row (Prisma field names, dates as ISO strings).');
out('    pub fn to_json(&self) -> serde_json::Value { <Self as Model>::to_json(self) }');
out();
out('    /// Reads a cached JSON object (extra keys such as `_cacheV` are ignored; absent optional fields are `None`).');
out('    pub fn from_json(value: &serde_json::Value) -> Result<Self, crate::DbError> { <Self as Model>::from_json(value) }');
out('}');
out();

out('/// Every model of the schema, in schema order.');
out(`pub static MODELS: &[&ModelInfo] = &[${infoNames.map((n) => `&${n}`).join(', ')}];`);
out();

out('/// Parses a cached JSON text as the named model and writes it back (`None` for an unknown model name).');
out('/// The output is what `JSON.stringify` writes for the same Prisma row.');
out('pub fn reserialize_json(model: &str, raw: &str) -> Option<Result<String, crate::DbError>> {');
out('    fn go<T: Model>(raw: &str) -> Result<String, crate::DbError> {');
out('        let v = T::from_json_str(raw)?;');
out('        serde_json::to_string(&v).map_err(|e| crate::DbError::Json(e.to_string()))');
out('    }');
out('    Some(match model {');
for (const m of dmmf.models) out(`        ${str(m.name)} => go::<${m.name}>(raw),`);
out('        _ => return None,');
out('    })');
out('}');
out();

out('/// Runs a built SELECT / INSERT ... RETURNING / UPDATE ... RETURNING for the named model and returns every row as');
out('/// its cache JSON (`None` for an unknown model name). For code that works on models by name (dashboard, tests).');
out('pub async fn fetch_all_json<\'e, E: sqlx::PgExecutor<\'e>>(model: &str, q: &crate::BuiltQuery, exec: E) -> Option<Result<Vec<serde_json::Value>, crate::DbError>> {');
out('    async fn go<\'e, T: Model, E: sqlx::PgExecutor<\'e>>(q: &crate::BuiltQuery, exec: E) -> Result<Vec<serde_json::Value>, crate::DbError> {');
out('        Ok(q.fetch_all::<T, E>(exec).await?.iter().map(Model::to_json).collect())');
out('    }');
out('    Some(match model {');
for (const m of dmmf.models) out(`        ${str(m.name)} => go::<${m.name}, E>(q, exec).await,`);
out('        _ => return None,');
out('    })');
out('}');
out();

writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}: ${dmmf.models.length} models, ${dmmf.enums.length} enums`);
