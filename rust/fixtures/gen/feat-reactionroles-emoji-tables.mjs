// The Unicode properties UNICODE_EMOJI_RE uses, as V8 (Node's ICU) sees them, printed as Rust range tables for
// crates/feat-reactionroles/src/reaction_role_service/emoji_tables.rs (the Rust regex crate ships older Unicode data).
//
//   node rust/fixtures/gen/feat-reactionroles-emoji-tables.mjs > crates/.../emoji_tables.rs
const props = ['Extended_Pictographic', 'Emoji_Presentation', 'Emoji_Modifier', 'Regional_Indicator'];
const lines = [
  `//! The Unicode properties of \`UNICODE_EMOJI_RE\` as V8 sees them (Unicode ${process.versions.unicode}, ICU ${process.versions.icu}),`,
  '//! generated by `rust/fixtures/gen/feat-reactionroles-emoji-tables.mjs`. Inclusive code point ranges.',
  '',
];
for (const p of props) {
  const re = new RegExp(String.raw`^\p{${p}}$`, 'u');
  const ranges = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const inSet = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (inSet && start < 0) start = cp;
    if (!inSet && start >= 0) { ranges.push([start, cp - 1]); start = -1; }
  }
  const name = p.toUpperCase();
  lines.push(`pub const ${name}: &[(u32, u32)] = &[`);
  for (let i = 0; i < ranges.length; i += 6) {
    lines.push('    ' + ranges.slice(i, i + 6).map(([a, b]) => `(0x${a.toString(16).toUpperCase()}, 0x${b.toString(16).toUpperCase()})`).join(', ') + ',');
  }
  lines.push('];', '');
}
process.stdout.write(lines.join('\n'));
