// Generates rust/crates/feat-translation/src/intl_data.rs from Node's ICU: the English language names
// Intl.DisplayNames gives for 2- and 3-letter codes (translationService.languageName for codes outside LANGUAGES),
// and the codes whose likely script is Latin (Intl.Locale(code).maximize().script, used by reconcileDetected).
//
//   node rust/fixtures/gen/feat-translation-intl.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const names = new Intl.DisplayNames(['en'], { type: 'language' });
const a = 'abcdefghijklmnopqrstuvwxyz';
const codes = [];
for (const x of a) for (const y of a) codes.push(x + y);
for (const x of a) for (const y of a) for (const z of a) codes.push(x + y + z);
const named = [];
const latn = [];
for (const code of codes) {
  let name = null;
  try { name = names.of(code); } catch { name = null; }
  if (name && name !== code) named.push([code, name]);
  let script = null;
  try { script = new Intl.Locale(code).maximize().script; } catch { script = null; }
  if (script === 'Latn') latn.push(code);
}
const esc = (s) => JSON.stringify(s);
const out = [
  '//! Generated by `node rust/fixtures/gen/feat-translation-intl.mjs` from Node\'s ICU (do not edit by hand).',
  `//! ICU ${process.versions.icu}, CLDR ${process.versions.cldr ?? '?'}.`,
  '',
  '/// `new Intl.DisplayNames([\'en\'], { type: \'language\' }).of(code)` for every 2- and 3-letter code it names.',
  'pub(crate) static LANGUAGE_NAMES: &[(&str, &str)] = &[',
  ...named.map(([c, n]) => `    (${esc(c)}, ${esc(n)}),`),
  '];',
  '',
  '/// The 2- and 3-letter codes whose likely script (`new Intl.Locale(code).maximize().script`) is `Latn`.',
  'pub(crate) static LATIN_SCRIPT_CODES: &[&str] = &[',
  ...latn.map((c) => `    ${esc(c)},`),
  '];',
  '',
];
writeFileSync(join(ROOT, 'rust', 'crates', 'feat-translation', 'src', 'intl_data.rs'), out.join('\n'));
console.log(`names ${named.length}, latn ${latn.length}`);
